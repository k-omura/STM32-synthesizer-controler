static fb_color24_t neopixel_fb[NEOPIXEL_PIXELS] = {0};
static uint8_t neopixel_fb_raw[NEOPIXEL_PIXELS_RAW] = {0};
static uint8_t neopixel_type = 0;

// support function
void neopixel_translate();
void neopixel_translate_col(uint8_t, uint8_t *);

//
void neopixel_flush(SPI_HandleTypeDef *hspi)
{
	if (HAL_SPI_GetState(hspi) != HAL_SPI_STATE_READY)
	{
		return;
	}

	neopixel_translate();
	HAL_SPI_Transmit_DMA(hspi, neopixel_fb_raw, NEOPIXEL_PIXELS_RAW);
}

void neopixel_settype(uint8_t _type)
{
	neopixel_type = _type;
	return;
}

void neopixel_translate()
{
	uint8_t *fb = neopixel_fb_raw;
	*fb++ = 0;

	for (uint16_t i = 0; i < NEOPIXEL_PIXELS; i++)
	{
		neopixel_translate_col(neopixel_fb[i].green, fb);
		fb += 4;
		neopixel_translate_col(neopixel_fb[i].red, fb);
		fb += 4;
		neopixel_translate_col(neopixel_fb[i].blue, fb);
		fb += 4;
	}
}

void neopixel_translate_col(uint8_t _code8, uint8_t *_fbraw_start)
{
	uint8_t temp;
	for (uint16_t i = 0; i < 4; i++)
	{
		temp = (_code8 & 0b10000000) ? (0b1110 << 4) : (0b1000 << 4);
		temp |= (_code8 & 0b01000000) ? (0b1110) : (0b1000);

		*_fbraw_start++ = temp;
		_code8 <<= 2;
	}
}

void neopixel_fb_pixel(int16_t _x, int16_t _y, fb_color24_t *_color)
{
	if ((_x < 0) || (_x >= NEOPIXEL_WIDTH) || (_y < 0) || (_y >= NEOPIXEL_HEIGHT))
	{
		return;
	}

	if (((_x % 2) == 1) && (neopixel_type == 1))
	{
		memcpy(neopixel_fb + (NEOPIXEL_HEIGHT * _x + ((NEOPIXEL_HEIGHT - 1) - _y)), _color, sizeof(fb_color24_t));
	}
	else
	{
		memcpy(neopixel_fb + (NEOPIXEL_HEIGHT * _x + _y), _color, sizeof(fb_color24_t));
	}
}

void neopixel_fb_pixel_rand(int16_t _x, int16_t _y)
{
	uint8_t temp;
	fb_color24_t pixel;

	temp = (uint8_t)rand();
	pixel.green = temp & 0x03;
	pixel.red = (temp >> 2) & 0x03;
	pixel.blue = (temp >> 4) & 0x03;

	neopixel_fb_pixel(_x, _y, &pixel);
}

void neopixel_fb_clear(fb_color24_t *_color)
{
	fb_color24_t *fb = neopixel_fb;
	for (uint16_t i = 0; i < NEOPIXEL_PIXELS; i++)
	{
		memcpy(fb++, _color, sizeof(fb_color24_t));
	}
}

void neopixel_fb_xbar(int16_t _x, int16_t _y, uint8_t _length, fb_color24_t *_color)
{
	for (uint8_t i = 0; i < _length; i++)
	{
		neopixel_fb_pixel(_x + i, _y, _color);
	}
}

void neopixel_fb_ybar(int16_t _x, int16_t _y, uint8_t _length, fb_color24_t *_color)
{
	for (uint8_t i = 0; i < _length; i++)
	{
		neopixel_fb_pixel(_x, _y + i, _color);
	}
}

void neopixel_fb_mosaic()
{
	fb_color24_t *fb = neopixel_fb;
	for (uint16_t i = 0; i < NEOPIXEL_PIXELS; i++)
	{
		uint8_t temp = (uint8_t)rand();
		(*fb).green = temp & 0x01;
		(*fb).red = (temp >> 2) & 0x01;
		(*fb++).blue = (temp >> 4) & 0x01;
	}
}

void neopixel_fb_logo(uint8_t _index, fb_color24_t *_color)
{
	uint8_t temp;
	if(_index > 1)
	{
		return;
	}

	for (uint16_t i = 0; i < 32; i++)
	{
		temp = OTAKURO_LOGO[_index][i];
		for (uint8_t b = 0; b < 8; b++)
		{
			if (temp & 0x80)
			{
				//neopixel_fb_pixel_rand(i, b);
				neopixel_fb_pixel(i, b, _color);
			}
			temp <<= 1;
		}
	}
}

void neopixel_fb_icon(seq_icon_t _icon, fb_color24_t *_color)
{
	uint8_t temp;
	if(_icon >= SEQ_ICON_COUNT)
	{
		return;
	}

	for (uint16_t i = 0; i < 8; i++)
	{
		temp = seq_icon[_icon][i];
		for (uint8_t b = 0; b < 8; b++)
		{
			if (temp & 0x80)
			{
				neopixel_fb_pixel(i, b, _color);
			}
			temp <<= 1;
		}
	}
}

void neopixel_fb_stringBitmap(int16_t _x, int16_t _y, const char _character[], uint8_t size, fb_color24_t *_color, uint8_t _font)
{
	uint8_t c = 0;
	while (_character[c])
	{
		if (size == 0)
		{
			neopixel_fb_characterBitmap5(&_x, _y, _character[c], _color);
		}
		else
		{
			neopixel_fb_characterBitmap8(&_x, _y, _character[c], _color, _font);
		}
		c++;
	}
}

void neopixel_fb_characterBitmap8(int16_t *_x, int16_t _y, char _character, fb_color24_t *_color, uint8_t _font)
{
	uint8_t minStart = 7;
	uint8_t maxWidth = 0;

	for (uint8_t y = 0; y < 8; y++)
	{
		uint16_t fontByte;
		fontByte = FONT8x8[_font][_character - 0x1F][y];

		for (uint8_t x = 0; x < 8; x++)
		{
			if (fontByte & 0x80)
			{
				uint8_t width = 8 - x;
				if (width > maxWidth)
				{
					maxWidth = width;
					minStart = x;
				}
				break;
			}
			fontByte <<= 1;
		}
	}

	for (uint8_t y = 0; y < 8; y++)
	{
		uint16_t fontByte;
		fontByte = FONT8x8[_font][_character - 0x1F][y];
		fontByte <<= minStart;

		for (uint8_t x = 0; x < maxWidth; x++)
		{
			if (fontByte & 0x80)
			{
				neopixel_fb_pixel(*_x + x, _y + y, _color);
			}
			fontByte <<= 1;
		}
	}

	*_x += maxWidth;
}

void neopixel_fb_characterBitmap5(int16_t *_x, int16_t _y, char _character, fb_color24_t *_color)
{
	uint8_t index = 0;

	for (uint8_t array = 0; array < 2; array++)
	{
		uint16_t fontByte;
		fontByte = FONT5x3[_character - 0x1F][array];

		for (uint8_t i = 0; i < 8; i++)
		{
			if (fontByte & 0x80)
			{
				neopixel_fb_pixel(*_x + (index % 3), _y + (index / 3), _color);
			}
			fontByte = fontByte << 1;
			index++;
		}
	}

	*_x += 4;
}

